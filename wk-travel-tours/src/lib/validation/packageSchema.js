import { z } from 'zod';

export const packageSchema = z.object({
  id: z.string().optional(),
  title: z.string().min(3, 'Title must be at least 3 characters').max(150),
  slug: z.string().min(3).max(150),
  destination: z.string().min(2, 'Destination is required'),
  subtitle: z.string().max(250).optional().nullable(),
  tagline: z.string().max(250).optional().nullable(),
  price: z.number().int().positive('Price must be a positive integer in PKR'),
  pricingBasis: z.enum(['per_person', 'fixed_group', 'visa_only']).default('per_person'),
  duration: z.string().min(2, 'Duration label is required'),
  durationDays: z.number().int().optional(),
  category: z.string().optional(),
  categories: z.array(z.string()).default([]),
  allowedCategories: z.array(z.string()).default([]),
  serviceType: z.enum(['tour', 'visa']).default('tour'),
  primaryImage: z.string().min(1, 'Primary image path is required'),
  galleryImages: z.array(z.string()).default([]),
  inclusions: z.array(z.string()).default([]),
  exclusions: z.array(z.string()).default([]),
  highlights: z.array(z.string()).default([]),
  itinerary: z.array(z.any()).default([]),
  isFeatured: z.boolean().default(false),
  isActive: z.boolean().default(true),
  isCustomized: z.boolean().default(false).optional(),
  packageType: z.string().default('standard').optional(),
  displayOrder: z.number().int().default(10).optional(),
  importantNotes: z.string().max(3000).optional().nullable(),
  disclaimer: z.string().max(1000).optional().nullable(),
  departureInfo: z.string().max(500).optional().nullable(),
  badge: z.string().max(100).optional().nullable(),
});
